// MAL'dan gelen türleri Türkçe karşılıklarına çeviren fonksiyon
export const translateGenres = (englishGenres: string): string => {
  if (!englishGenres) return "";

  const genreArray = englishGenres.split(", ");
  const translatedGenres = genreArray.map((genre) => {
    // Eğer çeviri tablosunda karşılığı varsa çevir, yoksa orijinal haliyle bırak
    return genreTranslations[genre] || genre;
  });

  // Çevrilen türleri virgülle ayırarak birleştir
  return translatedGenres.join(", ");
};
